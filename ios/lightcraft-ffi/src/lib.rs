//! LightCraft iOS bridge.
//!
//! The iOS app is another frontend of the LightCraft engine, like the desktop UI, the CLI and the
//! MCP server: it drives a `lightcraft_engine::Session` (through `lightcraft_mcp::Headless`, the
//! desktop's headless backend, which adds the desktop's `app.export`) with the same command ids
//! and JSON parameters (`develop.set`, `preset.apply`, `edit.undo`, `library.import`, …). New
//! commands upstream work here without changes to this crate.
//!
//! On top of [`Engine::call`] it adds what a frontend can't do through JSON: rendering previews and
//! thumbnails off the session lock (GPU through wgpu → Metal, CPU fallback, as the desktop's
//! render workers do), the slider specs in panel units (`controls`), and the panel layout
//! (`panel`).
//!
//! All hand-written code here is safe; the `unsafe` FFI glue is generated by uniffi's macros.
//! Every export returns a `Result`: uniffi turns an escaped panic into a thrown Swift error.
#![deny(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::unimplemented, clippy::todo, clippy::unreachable)]

use std::sync::{Arc, Mutex, MutexGuard, PoisonError};

use lightcraft_engine::Session;
use lightcraft_engine::catalog::PhotoId;
use lightcraft_engine::develop::{DevelopSettings, Treatment};
use lightcraft_engine::pipeline::Rendered;
use lightcraft_mcp::{Backend, Headless};
use serde_json::{Value, json};

mod controls;
mod panel;
pub use controls::ControlInfo;
pub use panel::{layout as panel_layout_value, placed_controls};

uniffi::setup_scaffolding!();

/// The GPU keeps at most this many bytes of recycled buffers.
const GPU_POOL_LIMIT: u64 = 256 << 20;
/// Largest preview or thumbnail edge a frontend may ask for.
const MAX_EDGE: u32 = 8192;

#[derive(Debug, thiserror::Error, uniffi::Error)]
pub enum LcError {
    #[error("{msg}")]
    Unsupported { msg: String },
    /// A command was refused (bad parameters, nothing selected, …): the engine's message.
    #[error("{msg}")]
    Command { msg: String },
    #[error("could not open the library: {msg}")]
    Library { msg: String },
    #[error("could not render: {msg}")]
    Render { msg: String },
}

/// A rendered image: display-encoded sRGB, 8-bit RGBA, row-major, `width * height * 4` bytes.
#[derive(uniffi::Record)]
pub struct Preview {
    pub width: u32,
    pub height: u32,
    pub rgba: Vec<u8>,
    /// Rendered on the GPU (false: the CPU pipeline).
    pub gpu: bool,
    pub histogram: Histogram,
}

/// The preview's 256-bin histogram (display-encoded values), as the desktop panel draws it.
#[derive(uniffi::Record)]
pub struct Histogram {
    pub r: Vec<u32>,
    pub g: Vec<u32>,
    pub b: Vec<u32>,
    pub luma: Vec<u32>,
    /// Share of pixels clipped to black / white in any channel.
    pub clipped_shadows: f32,
    pub clipped_highlights: f32,
}

/// What the Edit panel needs to know about the active photo beyond its develop settings.
#[derive(uniffi::Record)]
pub struct PhotoState {
    pub id: u64,
    /// Temp / Tint show the relative scale (rendered files, raws without a colour matrix).
    pub relative_wb: bool,
    /// Mirrors `ui-egui` `lib.rs` `is_bw`: B&W treatment or a monochrome profile.
    pub black_and_white: bool,
    pub hdr: bool,
    pub edited: bool,
    /// The file carries lens corrections (DNG opcodes): the lens profile sliders apply.
    pub has_lens: bool,
    /// AI Denoise applies to this photo (a raw).
    pub denoise_applicable: bool,
    pub profile_id: String,
    pub profile_name: String,
    /// The desktop panel's capture line: "ISO 3200 · 135mm · f/8.0 · 1/250" (empty without EXIF).
    pub capture: String,
    /// The White Balance menu's current entry ("As Shot", "Custom", …).
    pub wb_mode_label: String,
    /// The Point Color samples' swatches (`#rrggbb`), as the desktop draws them.
    pub point_colors: Vec<String>,
    /// The develop settings as JSON (`develop.get`): curve points, vignette style, white balance mode…
    pub settings_json: String,
}

/// The Curve editor's data for one channel.
#[derive(uniffi::Record)]
pub struct CurveInfo {
    /// The point curve's points (x0, y0, x1, y1, …), 0…1; empty for the parametric channel.
    pub points: Vec<f64>,
    /// The curve drawn at x = i / 96, i = 0…96 (the desktop draws the same samples).
    pub samples: Vec<f64>,
    /// The point-curve preset the curves match ("Linear", "Medium Contrast", …), or "Custom".
    pub preset: String,
    /// Every point-curve preset, built-in first.
    pub presets: Vec<String>,
}

/// One White Balance menu entry: the `develop.wb` mode id and its label.
#[derive(uniffi::Record)]
pub struct WbModeItem {
    pub id: String,
    pub label: String,
}

/// The White Balance menu (`develop.wb` modes; Custom is what moving Temp / Tint selects).
#[uniffi::export]
pub fn wb_modes() -> Result<Vec<WbModeItem>, LcError> {
    use lightcraft_engine::develop::WbMode;
    Ok(WbMode::ALL
        .iter()
        .filter(|m| **m != WbMode::Custom)
        .map(|m| WbModeItem {
            id: serde_json::to_value(m).ok().and_then(|v| v.as_str().map(str::to_string)).unwrap_or_default(),
            label: m.label().to_string(),
        })
        .collect())
}

/// A Point Color swatch. Mirrors `ui-egui` `panels/edit.rs` `oklch_color`.
fn oklch_color(l: f64, c: f64, h_deg: f64) -> String {
    use lightcraft_color::perceptual::{lch_to_lab, oklab_to_2020};
    let lin = oklab_to_2020(lch_to_lab([l as f32, c as f32, (h_deg as f32).to_radians()]));
    let s = lightcraft_color::REC2020.to_space(&lightcraft_color::SRGB).apply_f32(lin);
    let e = s.map(|v| (lightcraft_color::transfer::linear_to_srgb(v.clamp(0.0, 1.0)) * 255.0).round() as u8);
    format!("#{:02x}{:02x}{:02x}", e[0], e[1], e[2])
}

/// GPU status for the UI: the adapter name, or why rendering stays on the CPU.
#[uniffi::export]
pub fn gpu_status() -> Result<String, LcError> {
    Ok(if lightcraft_engine::gpu::available() {
        lightcraft_engine::gpu::adapter_name().unwrap_or_else(|| "GPU".into())
    } else {
        lightcraft_engine::gpu::unavailable_reason().unwrap_or_else(|| "GPU unavailable".into())
    })
}

/// The desktop panel's layout as JSON (see `panel.rs`).
#[uniffi::export]
pub fn panel_layout() -> Result<String, LcError> {
    Ok(panel::layout().to_string())
}

/// Whether Temp / Tint show the relative scale: everything but a raw edited in Kelvin. Mirrors
/// `ui-egui` `panels/edit.rs` (`let raw = …develops_raw() && !p.relative_wb()`, Kelvin sliders when `raw`).
fn relative_scale(p: &lightcraft_engine::catalog::Photo) -> bool {
    !(p.develops_raw() && !p.relative_wb())
}

fn is_bw(d: &DevelopSettings) -> bool {
    d.treatment == Treatment::Bw || d.profile.id == "lc.mono" || d.profile.id.starts_with("lc.bw.")
}

/// The desktop's capture line (`panels/edit.rs` `histogram`): ISO, focal length, aperture, shutter.
fn capture_line(m: &lightcraft_engine::catalog::Meta) -> String {
    let shutter = (!m.shutter.is_empty()).then(|| m.shutter.clone());
    [m.iso.map(|i| format!("ISO {i}")), m.focal_mm.map(|f| format!("{f:.0}mm")), m.aperture.map(|a| format!("f/{a:.1}")), shutter]
        .into_iter()
        .flatten()
        .collect::<Vec<_>>()
        .join(" · ")
}

fn to_preview(r: Rendered, gpu: bool) -> Result<Preview, LcError> {
    let img = r.image;
    let (Ok(width), Ok(height)) = (u32::try_from(img.width), u32::try_from(img.height)) else {
        return Err(LcError::Render { msg: "image too large".into() });
    };
    let h = r.histogram;
    let (clipped_shadows, clipped_highlights) = h.clipping();
    let histogram = Histogram { r: h.r, g: h.g, b: h.b, luma: h.luma, clipped_shadows, clipped_highlights };
    let rgba = img.data.into_iter().flatten().collect();
    Ok(Preview { width, height, rgba, gpu, histogram })
}

/// One open library and its session.
#[derive(uniffi::Object)]
pub struct Engine {
    h: Mutex<Headless>,
}

#[uniffi::export]
impl Engine {
    /// Open (or create) the library in `library_dir`. `models_dir`: where AI models would be kept.
    /// `memory_mb`: the caches' memory budget (0: the engine's default).
    #[uniffi::constructor]
    pub fn open(library_dir: String, models_dir: String, memory_mb: u32) -> Result<Arc<Self>, LcError> {
        lightcraft_engine::gpu::set_pool_limit(GPU_POOL_LIMIT);
        lightcraft_engine::gpu::warm_up();
        let mut session = Session::new().with_fs().with_system_clock();
        session.face_models_dir = Some(models_dir.into());
        session.open_library(&library_dir, false).map_err(|e| LcError::Library { msg: e.to_string() })?;
        let engine = Engine { h: Mutex::new(Headless::new(session)) };
        engine.relink_moved_originals();
        if memory_mb > 0 {
            engine.call("app.memoryBudget".into(), json!({"mb": memory_mb}).to_string())?;
        }
        Ok(Arc::new(engine))
    }

    /// Run a command (`develop.set`, `preset.apply`, `edit.undo`, `app.export`, …) with JSON
    /// parameters; returns its JSON result. The same ids and parameters as the desktop app, the
    /// CLI and MCP (`engine.commands` lists them).
    pub fn call(&self, command: String, params_json: String) -> Result<String, LcError> {
        let params: Value = if params_json.trim().is_empty() {
            json!({})
        } else {
            serde_json::from_str(&params_json).map_err(|e| LcError::Command { msg: format!("bad JSON for {command}: {e}") })?
        };
        let method = if command == "engine.commands" { "engine.commands" } else { "command" };
        self.lock().call(method, json!({"command": command, "params": params})).map(|v| v.to_string()).map_err(|msg| LcError::Command { msg })
    }

    /// The active photo's state for the Edit panel (`None`: no photo).
    pub fn photo_state(&self) -> Result<Option<PhotoState>, LcError> {
        let h = self.lock();
        let s = &h.session;
        let Some(id) = s.active() else { return Ok(None) };
        let Some(p) = s.catalog.photo(id) else { return Ok(None) };
        let d = s.develop_of(id).unwrap_or_default();
        let profile_name = s.profile_info(&d.profile.id).map(|(name, _)| name.to_string()).unwrap_or_else(|| "Color".into());
        Ok(Some(PhotoState {
            id: id.0,
            relative_wb: relative_scale(p),
            black_and_white: is_bw(&d),
            hdr: d.hdr.enabled,
            edited: p.is_edited(),
            has_lens: p.embedded_lens.is_some(),
            denoise_applicable: !matches!(s.denoise_photo_state(id), lightcraft_engine::denoise::PhotoState::NotApplicable),
            profile_id: d.profile.id.clone(),
            profile_name,
            capture: capture_line(&p.meta),
            wb_mode_label: d.wb.mode.label().to_string(),
            point_colors: d.point_colors.iter().map(|c| oklch_color(c.lum, c.chroma, c.hue)).collect(),
            settings_json: serde_json::to_string(&*d).unwrap_or_default(),
        }))
    }

    /// Every develop control of the active photo, in panel units.
    pub fn controls(&self) -> Result<Vec<ControlInfo>, LcError> {
        let h = self.lock();
        let s = &h.session;
        let id = s.active();
        let d = id.and_then(|id| s.develop_of(id)).unwrap_or_default();
        let relative = id.and_then(|id| s.catalog.photo(id)).is_none_or(|p| relative_scale(p));
        Ok(controls::all(&d, relative))
    }

    /// Set one slider of the active photo (panel units, through `develop.set`). Returns the value
    /// kept: clamped and on the control's steps.
    pub fn set_value(&self, id: String, value: f64) -> Result<f64, LcError> {
        let relative = self.relative_wb();
        let spec = controls::spec(&id, relative).ok_or_else(|| LcError::Unsupported { msg: format!("unknown control `{id}`") })?;
        let v = controls::snap(&spec, value);
        self.call("develop.set".into(), json!({"control": id, "value": controls::engine_value(&id, v, relative)}).to_string())?;
        let h = self.lock();
        let d = h.session.active().and_then(|a| h.session.develop_of(a)).unwrap_or_default();
        Ok(controls::value(&d, &id, relative))
    }

    /// Render `photo` to fit `max_edge` (long edge), off the session lock. `draft`: the interactive
    /// quality used while a slider is dragged; `before`: the photo's "before" state.
    pub fn render(&self, photo: u64, max_edge: u32, draft: bool, before: bool) -> Result<Preview, LcError> {
        let edge = max_edge.clamp(16, MAX_EDGE) as usize;
        let job = {
            let mut h = self.lock();
            let job =
                h.session.render_job(PhotoId(photo), edge, edge, before, true).ok_or_else(|| LcError::Render { msg: "no such photo".into() })?;
            if draft { job.draft() } else { job }
        };
        self.finish(job.run())
    }

    /// A thumbnail of `photo` (its current edit) fitting `edge`.
    pub fn thumbnail(&self, photo: u64, edge: u32) -> Result<Preview, LcError> {
        let job = self
            .lock()
            .session
            .thumb_job(PhotoId(photo), edge.clamp(16, MAX_EDGE) as usize)
            .ok_or_else(|| LcError::Render { msg: "no such photo".into() })?;
        self.finish(job.run())
    }

    /// The Curve editor's points and drawn curve for `channel` (`parametric`, `master`, `red`,
    /// `green`, `blue`) of the active photo.
    pub fn curve(&self, channel: String) -> Result<CurveInfo, LcError> {
        use lightcraft_engine::cmd::curves::{all_presets, matching_preset};
        let h = self.lock();
        let s = &h.session;
        let d = s.active().and_then(|id| s.develop_of(id)).unwrap_or_default();
        let c = &d.curve;
        let presets: Vec<String> = all_presets(s).into_iter().map(|p| p.name).collect();
        let preset = matching_preset(s, c).unwrap_or_else(|| "Custom".into());
        if channel == "parametric" {
            // mirrors `ui-egui` `panels/edit.rs` `curve_editor` (its drawing of the parametric curve)
            let regions = [
                (0.0, c.split_shadows / 100.0, c.shadows),
                (c.split_shadows / 100.0, c.split_mid / 100.0, c.darks),
                (c.split_mid / 100.0, c.split_highlights / 100.0, c.lights),
                (c.split_highlights / 100.0, 1.0, c.highlights),
            ];
            let samples = (0..=96)
                .map(|i| {
                    let x = i as f64 / 96.0;
                    let mut dd = 0.0;
                    for (a, b, amt) in regions {
                        let (ctr, half) = ((a + b) / 2.0, (b - a) * 0.75 + 0.05);
                        let tt = ((x - ctr) / half).clamp(-1.0, 1.0);
                        dd += amt / 100.0 * 0.22 * (0.5 + 0.5 * (tt * std::f64::consts::PI).cos());
                    }
                    (x + dd * 4.0 * x * (1.0 - x)).clamp(0.0, 1.0)
                })
                .collect();
            return Ok(CurveInfo { points: Vec::new(), samples, preset, presets });
        }
        let v = match channel.as_str() {
            "red" => &c.red,
            "green" => &c.green,
            "blue" => &c.blue,
            _ => &c.master,
        };
        // an empty channel is the identity: the desktop shows its two end points
        let pts: Vec<(f64, f64)> = if v.is_empty() { vec![(0.0, 0.0), (1.0, 1.0)] } else { v.iter().map(|q| (q.x, q.y)).collect() };
        let curve = lightcraft_color::spline::MonotoneCurve::new(&pts);
        let samples = (0..=96).map(|i| curve.eval(i as f64 / 96.0).clamp(0.0, 1.0)).collect();
        Ok(CurveInfo { points: pts.iter().flat_map(|(x, y)| [*x, *y]).collect(), samples, preset, presets })
    }

    /// Write the library's pending changes to disk (the app is going to the background).
    pub fn save(&self) -> Result<(), LcError> {
        self.lock().session.persist().map_err(|e| LcError::Library { msg: e.to_string() })
    }
}

impl Engine {
    fn lock(&self) -> MutexGuard<'_, Headless> {
        self.h.lock().unwrap_or_else(PoisonError::into_inner)
    }

    /// iOS moves an app's data folder (a new container path) on reinstalls and updates, and the
    /// library records its photos' absolute paths: photos imported by copy, whose files are in the
    /// library's own Originals folder, are found again there (`library.findMissing`, the desktop's
    /// Find Missing Photos). Not an edit of the user's: it leaves no undo step.
    fn relink_moved_originals(&self) {
        let mut h = self.lock();
        let Some(originals) = h.session.library.as_ref().map(|l| l.originals_dir()) else { return };
        let missing = h.call("command", json!({"command": "library.missing", "params": {}}));
        if !missing.as_ref().is_ok_and(|m| m.as_array().is_some_and(|a| !a.is_empty())) {
            return;
        }
        let relinked = h.call("command", json!({"command": "library.findMissing", "params": {"folder": originals.to_string_lossy()}}));
        if relinked.is_ok() {
            h.session.undo.clear();
            h.session.redo.clear();
            let _ = h.session.persist();
        }
    }

    fn relative_wb(&self) -> bool {
        let h = self.lock();
        h.session.active().and_then(|id| h.session.catalog.photo(id)).is_none_or(|p| relative_scale(p))
    }

    /// Keep what the job loaded (decoded sources go to the session's caches) and return its image.
    fn finish(&self, r: lightcraft_engine::media::RenderResult) -> Result<Preview, LcError> {
        self.lock().session.accept(&r);
        let gpu = r.gpu_fallback.is_none() && lightcraft_engine::gpu::available();
        let rendered = r.rendered.map_err(|msg| LcError::Render { msg })?;
        to_preview(rendered, gpu)
    }
}

